import { icons, defaultIcon } from "../lib/icons";

export default function Icon({ name, size = 40 }) {
  const inner = icons[name] || icons[defaultIcon];
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.7"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: inner }}
    />
  );
}
